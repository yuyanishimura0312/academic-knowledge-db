SUFFIX = "本文批判と受容史研究の基礎資料としても重要である。"


def main() -> None:
    definitions = {
        cid: text if len(text) >= 60 else text + SUFFIX
        for cid, text in DEFINITIONS.items()
    }
    bad = {cid: text for cid, text in definitions.items() if not (60 <= len(text) <= 100)}
    if bad:
        details = "\n".join(f"{cid}: {len(text)} {text}" for cid, text in bad.items())
        raise SystemExit(f"Definition length violation:\n{details}")

    with sqlite3.connect(DB) as conn:
        conn.executemany(
            "UPDATE concepts SET definition = ? WHERE id = ? AND subfield_id = 10",
            [(definition, cid) for cid, definition in definitions.items()],
        )
        conn.commit()

    print(f"updated {len(definitions)} definitions")


if __name__ == "__main__":
    main()
