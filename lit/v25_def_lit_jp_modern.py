def main() -> None:
    updates = {
        concept_id: definition + SUFFIX
        for concept_id, definition in DEFINITIONS.items()
    }

    for concept_id, definition in updates.items():
        assert definition.strip(), concept_id
        assert 60 <= len(definition) <= 100, (concept_id, len(definition))

    with sqlite3.connect("lit.sqlite") as conn:
        conn.executemany(
            "UPDATE concepts SET definition = ? WHERE id = ?",
            [(definition, concept_id) for concept_id, definition in updates.items()],
        )
        conn.commit()


if __name__ == "__main__":
    main()
