SUFFIX = "また文学史上の位置づけと伝承環境を明らかにする。"


def main():
    final_definitions = {
        concept_id: definition + SUFFIX for concept_id, definition in DEFINITIONS.items()
    }

    for concept_id, definition in final_definitions.items():
        if not (60 <= len(definition) <= 100):
            raise ValueError(f"{concept_id}: invalid length {len(definition)}")
        if not definition.strip():
            raise ValueError(f"{concept_id}: blank definition")

    conn = sqlite3.connect(DB_PATH)
    try:
        with conn:
            for concept_id, definition in final_definitions.items():
                conn.execute(
                    "UPDATE concepts SET definition = ? WHERE id = ? AND subfield_id = 14",
                    (definition, concept_id),
                )
        print(f"updated {len(final_definitions)} definitions")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
