def infer_tag(name: str, definition: str) -> tuple[str, str, str, str]:
    text = f"{name} {definition}"
    if any(k in text for k in ("翻訳", "翻案", "移植", "受容", "紹介")):
        return ("翻訳", "rethinking", "翻訳・翻案を通じて文学的価値の移動と変形を問う", "文化翻訳")
    if any(k in text for k in ("詩", "語", "言語", "文体", "韻", "口語", "台詞")):
        return ("言語", "rethinking", "詩語・文体・発話形式が表現生成の単位を問い直す", "文体生成")
    if any(k in text for k in ("亡命", "流刑", "地下", "検閲", "禁書", "サミズダート")):
        return ("作者性", "rethinking", "検閲や越境状況が作者の発話位置と責任を変える", "越境作者")
    if any(k in text for k in ("証言", "回想", "戦争", "収容所", "粛清", "実録")):
        return ("真正性", "rethinking", "証言性と文学的構成の関係が真実性の基準を揺らす", "証言評価")
    if any(k in text for k in ("正典", "古典", "代表作", "国民", "ノーベル")):
        return ("正典", "partial", "後代の読解と制度的評価を通じて正典的位置を持つ", "正典推薦")
    if any(k in text for k in ("女性", "農民", "知識人", "主人公", "主体", "心理", "自己")):
        return ("主体", "rethinking", "人物像が近代的主体や周縁的主体の条件を問い直す", "主体モデル化")
    if any(k in text for k in ("象徴", "前衛", "未来派", "実験", "神秘", "幻想")):
        return ("創造性", "rethinking", "形式実験や幻想性が創造の規範を更新する", "創造支援")
    if any(k in text for k in ("読者", "出版", "雑誌", "劇場", "流通", "映画")):
        return ("受容", "rethinking", "媒体と読者圏が作品価値の形成を左右する", "受容分析")
    return ("物語", "rethinking", "構成・視点・ジャンルの選択が物語生成の条件を問い直す", "物語生成")


def main() -> None:
    with sqlite3.connect(DB_PATH, timeout=30) as conn:
        conn.execute("PRAGMA busy_timeout = 30000")
        before = conn.total_changes
        conn.executemany(
            """
            INSERT OR IGNORE INTO fourth_transform_tags
                (concept_id, axis, status, rationale, related_ai_phenomenon)
            VALUES (?, ?, ?, ?, ?)
            """,
            TAGS,
        )
        remaining = conn.execute(
            """
            SELECT c.id, c.name_ja, c.definition
            FROM concepts c
            LEFT JOIN fourth_transform_tags ftt ON ftt.concept_id = c.id
            WHERE c.subfield_id = 18 AND ftt.id IS NULL
            ORDER BY c.id
            """
        ).fetchall()
        inferred = [
            (concept_id, *infer_tag(name, definition or ""))
            for concept_id, name, definition in remaining
        ]
        conn.executemany(
            """
            INSERT OR IGNORE INTO fourth_transform_tags
                (concept_id, axis, status, rationale, related_ai_phenomenon)
            VALUES (?, ?, ?, ?, ?)
            """,
            inferred,
        )
        conn.commit()
        print(f"Inserted {conn.total_changes - before} fourth_transform_tags.")


if __name__ == "__main__":
    main()
