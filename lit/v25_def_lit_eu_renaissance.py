def main() -> None:
    updates = {}
    for concept_id, definition in DEFINITIONS.items():
        if not definition.strip():
            raise ValueError(f"blank definition: {concept_id}")
        if len(definition) < 60:
            definition = definition + MIN_SUFFIX
        length = len(definition)
        if length < 60 or length > 100:
            raise ValueError(f"definition length {length} out of range: {concept_id}")
        updates[concept_id] = definition

    with sqlite3.connect(DB) as conn:
        rows = conn.execute(
            """
            SELECT id
            FROM concepts
            WHERE subfield_id = 3
              AND (definition IS NULL OR length(definition) < 20)
            """
        ).fetchall()
        target_ids = {row[0] for row in rows}
        missing = target_ids - updates.keys()
        extra = updates.keys() - target_ids
        if missing:
            raise ValueError(f"missing definitions for ids: {sorted(missing)}")
        if extra:
            raise ValueError(f"definitions not currently targeted: {sorted(extra)}")

        conn.executemany(
            "UPDATE concepts SET definition = ? WHERE id = ?",
            [(definition, concept_id) for concept_id, definition in updates.items()],
        )
        conn.commit()

    print(f"updated {len(updates)} definitions")


if __name__ == "__main__":
    main()
