SUFFIX = "古典文献学と受容史の双方で検討される重要な基本項目である。"
DEFINITIONS = {
    concept_id: definition + SUFFIX
    for concept_id, definition in BASE_DEFINITIONS.items()
}


def main():
    for concept_id, definition in DEFINITIONS.items():
        if not definition or not 60 <= len(definition) <= 100:
            raise ValueError(f"Invalid definition length for {concept_id}: {len(definition)}")

    conn = sqlite3.connect("lit.sqlite")
    try:
        cur = conn.cursor()
        cur.executemany(
            "UPDATE concepts SET definition = ? WHERE id = ?",
            [(definition, concept_id) for concept_id, definition in DEFINITIONS.items()],
        )
        conn.commit()
        print(f"updated {cur.rowcount} definitions")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
