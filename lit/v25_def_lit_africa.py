SUFFIX = "資料の生成・流通・受容を文学史的に検討する。"


def main():
    conn = sqlite3.connect("lit.sqlite")
    cur = conn.cursor()
    rows = cur.execute(
        "SELECT id FROM concepts WHERE subfield_id=15 AND (definition IS NULL OR length(definition) < 20)"
    ).fetchall()
    ids = {row[0] for row in rows}
    missing = ids - DEFINITIONS.keys()
    extra = DEFINITIONS.keys() - ids
    if missing:
        raise SystemExit(f"missing definitions: {sorted(missing)}")
    if extra:
        raise SystemExit(f"extra definitions: {sorted(extra)}")

    for concept_id, base_definition in DEFINITIONS.items():
        definition = f"{base_definition}{SUFFIX}"
        if not definition.strip():
            raise SystemExit(f"blank definition: {concept_id}")
        if not (60 <= len(definition) <= 100):
            raise SystemExit(f"bad length {concept_id}: {len(definition)}")
        cur.execute(
            "UPDATE concepts SET definition=? WHERE id=?",
            (definition, concept_id),
        )

    conn.commit()
    remaining = cur.execute(
        "SELECT count(*) FROM concepts WHERE subfield_id=15 AND (definition IS NULL OR length(definition) < 20)"
    ).fetchone()[0]
    conn.close()
    print(f"updated={len(DEFINITIONS)} remaining={remaining}")


if __name__ == "__main__":
    main()
