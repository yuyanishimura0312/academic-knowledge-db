def main() -> None:
    inserted = []
    with LitDB("lit.sqlite") as db:
        for _, (period_name, concepts) in CLUSTERS.items():
            period_id = db.get_or_create_period(period_name, REGION)
            for name_ja, definition in concepts:
                cid = db.insert_concept(
                    name_ja=name_ja,
                    subfield_code=SUBFIELD,
                    region=REGION,
                    period_id=period_id,
                    definition=definition,
                    importance_score=2,
                    source_tier="tertiary",
                    canonical_in_region="marginal",
                )
                inserted.append(cid)
    print(f"inserted_or_existing={len(inserted)}")


if __name__ == "__main__":
    main()
