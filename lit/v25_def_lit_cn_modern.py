def main():
    con = sqlite3.connect("lit.sqlite")
    cur = con.cursor()
    rows = cur.execute(
        "SELECT id FROM concepts WHERE subfield_id=9 AND (definition IS NULL OR length(definition) < 20)"
    ).fetchall()
    ids = {row[0] for row in rows}
    missing = ids - DEFINITIONS.keys()
    extra = DEFINITIONS.keys() - ids
    if missing:
        raise SystemExit(f"missing definitions: {sorted(missing)}")
    if extra:
        raise SystemExit(f"extra definitions: {sorted(extra)}")
    for cid, definition in DEFINITIONS.items():
        if not definition or len(definition) > 100:
            raise SystemExit(f"invalid length for {cid}: {len(definition)}")
        cur.execute("UPDATE concepts SET definition=? WHERE id=?", (definition, cid))
    con.commit()
    remaining = cur.execute(
        "SELECT COUNT(*) FROM concepts WHERE subfield_id=9 AND (definition IS NULL OR length(definition) < 20)"
    ).fetchone()[0]
    con.close()
    print(f"updated={len(DEFINITIONS)} remaining={remaining}")


if __name__ == "__main__":
    main()
