def main() -> None:
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    cur.execute(
        """
        SELECT c.id
        FROM concepts c
        LEFT JOIN fourth_transform_tags ftt ON ftt.concept_id = c.id
        WHERE c.subfield_id = 8 AND ftt.id IS NULL
        LIMIT 80
        """
    )
    targets = {row[0] for row in cur.fetchall()}

    before = conn.total_changes
    for concept_id, axis, status, rationale, phenomenon in TAGS:
        if concept_id not in targets:
            continue
        cur.execute(
            """
            INSERT OR IGNORE INTO fourth_transform_tags
                (concept_id, axis, status, rationale, related_ai_phenomenon)
            VALUES (?, ?, ?, ?, ?)
            """,
            (concept_id, axis, status, rationale, phenomenon),
        )
    conn.commit()
    print(conn.total_changes - before)
    conn.close()


if __name__ == "__main__":
    main()
