def best_canonical(domain: str, raw: str, name_en: str = "", keywords_en: str = "") -> str | None:
    canon = TAXONOMY["domains"][domain]["subfields"]
    rules = RULES[domain]
    # Exact match if raw is already canonical
    if raw and raw in canon:
        return raw
    # Rule-based keyword match against subfield name
    if raw:
        for canonical_name, keywords in rules:
            for kw in keywords:
                if kw.lower() in raw.lower():
                    return canonical_name
    # Fallback: try matching against name_en and keywords_en
    haystack = f"{name_en} {keywords_en}".lower()
    if haystack.strip():
        for canonical_name, keywords in rules:
            for kw in keywords:
                if kw.lower() in haystack:
                    return canonical_name
    return None  # truly unmappable


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--commit", action="store_true")
    p.add_argument("--domain", help="Only normalize this domain")
    args = p.parse_args()

    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    summary = {}
    for domain in TAXONOMY["domains"]:
        if args.domain and args.domain != domain:
            continue
        rows = list(conn.execute(f"SELECT id, subfield, name_en, keywords_en FROM {domain}"))
        mapped = 0
        unmapped = []
        unmapped_counts = {}
        updates = []
        for r in rows:
            raw = r["subfield"] or ""
            canon = best_canonical(domain, raw, r["name_en"] or "", r["keywords_en"] or "")
            if canon and canon != raw:
                mapped += 1
                updates.append((canon, r["id"]))
            elif not canon:
                # Fallback to "未分類" so DB stays clean
                updates.append(("未分類", r["id"]))
                unmapped.append(raw)
                unmapped_counts[raw] = unmapped_counts.get(raw, 0) + 1
        summary[domain] = {
            "total": len(rows),
            "mapped": mapped,
            "unmapped_unique": len(set(unmapped)),
            "unmapped_total": len(unmapped),
        }
        print(f"\n[{domain}] total={len(rows)} mapped={mapped} unmapped={len(unmapped)} ({len(set(unmapped))} unique)")
        # show top unmapped
        top_unmapped = sorted(unmapped_counts.items(), key=lambda x: -x[1])[:10]
        for sf, c in top_unmapped:
            print(f"    UNMAPPED: {sf} ({c})")
        if args.commit and updates:
            conn.executemany(f"UPDATE {domain} SET subfield = ?, updated_at = datetime('now') WHERE id = ?", updates)
            print(f"  → committed {len(updates)} updates")

    if args.commit:
        conn.commit()
    conn.close()
    print("\n=== SUMMARY ===")
    for d, s in summary.items():
        print(f"  {d}: {s}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
