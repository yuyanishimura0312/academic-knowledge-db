def insert_batch(concepts):
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    cur.execute('SELECT name_en FROM natural_discovery WHERE name_en IS NOT NULL')
    existing = set(r[0].lower().strip() for r in cur.fetchall())

    inserted = 0
    skipped = 0
    now = datetime.utcnow().isoformat()

    for c in concepts:
        name_en = c['name_en'].lower().strip()
        if name_en in existing:
            skipped += 1
            continue
        try:
            cur.execute('''INSERT INTO natural_discovery
            (id,name_ja,name_en,name_original,definition,impact_summary,subfield,school_of_thought,
             era_start,era_end,methodology_level,target_domain,application_conditions,when_to_apply,
             framing_questions,opposing_concept_names,keywords_ja,keywords_en,status,source_reliability,
             data_completeness,created_at,updated_at,mathematical_formulation,experimental_verification,
             applicable_scale,precision_level,quality_flag,source_url,primary_source,primary_source_url,
             primary_source_year,verification_status,culture_region,culture_confidence,genealogy_narrative,
             narrative_word_count,gta_l3,gta_l2,last_verified_at,redirect_to,http_status)
            VALUES (:id,:name_ja,:name_en,:name_original,:definition,:impact_summary,:subfield,
             :school_of_thought,:era_start,:era_end,:methodology_level,:target_domain,
             :application_conditions,:when_to_apply,:framing_questions,:opposing_concept_names,
             :keywords_ja,:keywords_en,:status,:source_reliability,:data_completeness,
             :created_at,:updated_at,:mathematical_formulation,:experimental_verification,
             :applicable_scale,:precision_level,:quality_flag,:source_url,:primary_source,
             :primary_source_url,:primary_source_year,:verification_status,:culture_region,
             :culture_confidence,:genealogy_narrative,:narrative_word_count,:gta_l3,:gta_l2,
             :last_verified_at,:redirect_to,:http_status)''',
            {**c, 'created_at': now, 'updated_at': now})
            existing.add(name_en)
            inserted += 1
        except Exception as e:
            print(f"ERROR {c['id']}: {e}")
            skipped += 1

    conn.commit()
    cur.execute('SELECT COUNT(*) FROM natural_discovery')
    total = cur.fetchone()[0]
    conn.close()
    return inserted, skipped, total

if __name__ == '__main__':
    ins, sk, total = insert_batch(CONCEPTS)
    print(f"挿入: {ins}, スキップ: {sk}, DB総件数: {total}")
